    private void ingresarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_ingresarActionPerformed
        // TODO add your handling code here:
        String usuario = txtusuario.getText().trim();
        String clave = new String(contra.getPassword());
        
        if(usuario.isEmpty() || clave.isEmpty()){
            JOptionPane.showMessageDialog(this, "Complete todos los espacios", "Aviso", JOptionPane.WARNING_MESSAGE);
            return;
        }
        String rol = validar(usuario,clave);
        
        if( rol == null){
            JOptionPane.showMessageDialog(this, "Usuario o contraseña incorrectos", "Error", JOptionPane.ERROR_MESSAGE);
            contra.setText("");
            return;
        }
        
        JOptionPane.showMessageDialog(this,"Bienvenido, " + usuario + " (" +  rol + ")");
        
           // Login correcto: abrir el menú y cerrar el login
    MenuPrincipal menu = new MenuPrincipal(rol);
    menu.setVisible(true);
    this.dispose();
        
    }//GEN-LAST:event_ingresarActionPerformed

